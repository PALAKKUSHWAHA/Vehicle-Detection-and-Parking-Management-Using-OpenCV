def process_frame(frame):
    frame = cv2.resize(frame, (640, 480))
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    blurred = cv2.GaussianBlur(gray, (5, 5), 0)
    hist_eq = cv2.equalizeHist(blurred)

    orb = cv2.ORB_create()
    keypoints, _ = orb.detectAndCompute(hist_eq, None)
    features = cv2.drawKeypoints(frame, keypoints, None, color=(0, 255, 0))

    edges = cv2.Canny(hist_eq, 100, 200)
    return frame, features, edges

