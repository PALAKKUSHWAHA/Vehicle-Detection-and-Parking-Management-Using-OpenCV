# Perspective Transform on first few images
for i, image_path in enumerate(image_files[:3]):  # Limit for demo
    image = cv2.imread(image_path)
    h, w = image.shape[:2]

    # Define 4 source points (corners from an angled area)
    src_pts = np.float32([
        [w * 0.1, h * 0.3],  # Top-left
        [w * 0.9, h * 0.3],  # Top-right
        [w * 0.05, h * 0.9], # Bottom-left
        [w * 0.95, h * 0.9]  # Bottom-right
    ])

    # Define 4 destination points for top-down view
    dst_pts = np.float32([
        [0, 0],
        [w, 0],
        [0, h],
        [w, h]
    ])

    # Get perspective transform matrix and apply it
    matrix = cv2.getPerspectiveTransform(src_pts, dst_pts)
    warped = cv2.warpPerspective(image, matrix, (w, h))

    # Show original and warped (top-down) images
    plt.figure(figsize=(12, 6))

    plt.subplot(1, 2, 1)
    plt.imshow(cv2.cvtColor(image, cv2.COLOR_BGR2RGB))
    plt.title('Original (Angled View)')
    plt.axis('off')

    plt.subplot(1, 2, 2)
    plt.imshow(cv2.cvtColor(warped, cv2.COLOR_BGR2RGB))
    plt.title('Perspective Transformed (Top-Down View)')
    plt.axis('off')

    plt.show()
